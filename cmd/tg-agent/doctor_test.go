package main

import (
	"errors"
	"strings"
	"testing"
)

func TestParseNameservers(t *testing.T) {
	got := parseNameservers("# Generated by NetworkManager\nsearch example.org\nnameserver 172.23.1.3\nnameserver 192.168.178.1\n")
	if strings.Join(got, " ") != "172.23.1.3 192.168.178.1" {
		t.Errorf("got %v", got)
	}
}

func TestIsNetworkError(t *testing.T) {
	if !isNetworkError(errors.New("telegram getMe: dial tcp: i/o timeout")) {
		t.Error("a timeout is a network error")
	}
	if isNetworkError(errors.New("telegram getMe: Not Found")) || isNetworkError(nil) {
		t.Error("an answer from Telegram is not a network error")
	}
}
